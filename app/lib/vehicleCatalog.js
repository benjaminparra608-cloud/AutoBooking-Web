// Helper para calcular litros y costo en CLP según km
export function calcularGastoCombustible(kmRecorridos, vehiculo, tipoConduccion = 'mixto') {
  if (!vehiculo || kmRecorridos <= 0) {
    return { litros: 0, costoTotalCLP: 0, costoPorKmCLP: 0 };
  }

  const rendimiento =
    tipoConduccion === 'ciudad'
      ? vehiculo.rendimientoCiudad
      : tipoConduccion === 'carretera'
      ? vehiculo.rendimientoCarretera
      : vehiculo.rendimientoMixto;

  const litros = Number((kmRecorridos / rendimiento).toFixed(2));
  const precioLitro = PRECIOS_COMBUSTIBLE_CHILE[vehiculo.tipoCombustibleKey] || PRECIOS_COMBUSTIBLE_CHILE.bencina95;
  const costoTotalCLP = Math.round(litros * precioLitro);
  const costoPorKmCLP = Math.round(costoTotalCLP / kmRecorridos);

  return {
    litros,
    costoTotalCLP,
    costoPorKmCLP,
    precioLitro,
    rendimiento
  };
}
